#pragma once

#include "Systems/Physics/Events/ContactPoint2D.h"
#include "Utilities/Math/Vector2.h"

#include <span>
#include <vector>

// Contains collision details for 2D physics callbacks, including the involved colliders,
// rigid bodies, and contact points.
// Exposed scene objects are non-owning pointers valid only for the duration of the callback.
// Do not retain Collision2D references across frames.

namespace CaledonEngine
{
	class Collider2D;
	class GameObject;
	class RigidBody2D;
	class Transform;

	class Collision2D
	{
	private:
		Collider2D* m_pCollider;																									// The incoming Collider2D involved in this Collision2D event
		Collider2D* m_pOtherCollider;																								// The other Collider2D involved in this Collision2D event
		RigidBody2D* m_pRigidBody;																									// The incoming RigidBody2D involved in this Collision2D event
		RigidBody2D* m_pOtherRigidBody;																								// The other RigidBody2D involved in this Collision2D event
		Vector2f m_relativeVelocity;																								// The relative velocity of the two colliders at the time of collision
		std::vector<ContactPoint2D> m_contacts;																						// The contact points generated by the collision
		bool m_enabled;																												// Whether the collision is enabled (can be disabled in callbacks to ignore the collision)

	public:
		Collision2D(Collider2D* pCollider, Collider2D* pOtherCollider,																// Constructor
			RigidBody2D* pRigidBody, RigidBody2D* pOtherRigidBody,
			const Vector2f& relativeVelocity)
			: m_pCollider{ pCollider }
			, m_pOtherCollider{ pOtherCollider }
			, m_pRigidBody{ pRigidBody }
			, m_pOtherRigidBody{ pOtherRigidBody }
			, m_relativeVelocity{ relativeVelocity }
			, m_enabled{ true }
		{ }

		void Reset(Collider2D* pCollider, Collider2D* pOtherCollider,																// Reuses this object for another callback (keeps the contact storage)
			RigidBody2D* pRigidBody, RigidBody2D* pOtherRigidBody, const Vector2f& relativeVelocity)
		{
			m_pCollider = pCollider;
			m_pOtherCollider = pOtherCollider;
			m_pRigidBody = pRigidBody;
			m_pOtherRigidBody = pOtherRigidBody;
			m_relativeVelocity = relativeVelocity;
			m_contacts.clear();
			m_enabled = true;
		}

		Collider2D* GetCollider() const noexcept							{ return m_pCollider; }									// Returns the incoming Collider2D involved in this Collision2D event
		Collider2D* GetOtherCollider() const noexcept						{ return m_pOtherCollider; }							// Returns the other Collider2D involved in this Collision2D event
		RigidBody2D* GetRigidBody() const noexcept							{ return m_pRigidBody; }								// Returns the incoming RigidBody2D involved in this Collision2D event
		RigidBody2D* GetOtherRigidBody() const noexcept						{ return m_pOtherRigidBody; }							// Returns the other RigidBody2D involved in this Collision2D event
		const Vector2f& GetRelativeVelocity() const noexcept				{ return m_relativeVelocity; }							// Returns the relative velocity of the two colliders at the time of collision
		bool IsEnabled() const noexcept										{ return m_enabled; }									// Returns whether this Collision2D event is enabled
		void SetEnabled(bool enabled) noexcept								{ m_enabled = enabled; }								// Sets whether this Collision2D event is enabled

		GameObject* GetGameObject() const noexcept;																					// Returns the GameObject associated with the incoming Collider2D
		Transform* GetTransform() const noexcept;																					// Returns the Transform associated with the incoming Collider2D

		int GetContactCount() const noexcept								{ return static_cast<int>(m_contacts.size()); }			// Returns the number of contact points generated by this collision
		void AddContact(const ContactPoint2D& contact)						{ m_contacts.push_back(contact); }						// Adds a contact point to this collision

		std::span<const ContactPoint2D> GetContacts() const noexcept		{ return m_contacts; }									// Returns a span of the contact points generated by this collision

		/*-----------------------------------------------------------------------------------
		| --- GetContact: Returns a pointer to the contact point at the specified index --- |
		-----------------------------------------------------------------------------------*/
		const ContactPoint2D* GetContact(int index) const noexcept
		{
			if (index < 0 || index >= GetContactCount())
				return nullptr;

			return &m_contacts[static_cast<std::size_t>(index)];
		}

		/*--------------------------------------------------------------------------------------
		| --- GetContacts: Retuns the number of contact points copied to the provided span --- |
		--------------------------------------------------------------------------------------*/
		int GetContacts(std::span<ContactPoint2D> contacts) const noexcept
		{
			const std::size_t count = contacts.size() < m_contacts.size() ? contacts.size() : m_contacts.size();
			for (std::size_t i = 0; i < count; ++i)
			{
				contacts[i] = m_contacts[i];
			}

			return static_cast<int>(count);
		}
	};
}